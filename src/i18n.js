/** Resolve a supported language code, including regional values such as en-US. */
export function resolveLanguage(value) {
  const language = String(value || 'ru')
    .toLowerCase()
    .split('-')[0];
  return supportedLanguages.includes(language) ? language : 'ru';
}

/** Return UI copy for the selected language. */
export function getMessages(language) {
  return messages[resolveLanguage(language)];
}
